# Functions with parameters

def greet(name):
    print("Good Morning",name)

def add (num1,num2):


    answer=num1+num2
    print("The sum is",answer)



def divide(weight,height):


    answer=weight/height**height
    print("The division is",answer)




def simpleinterest(Principle,Rate,time):

    answer=Principle*Rate*time/100
    print("The simple interst is",answer)


def Area(Base,height):

    answer=Base*height/2
    print("The area is",answer)









greet("John")
greet("Joy")
add(12,13)
add(20,23)
divide(50,2.5)
simpleinterest(1000,0.5,3)
Area(20,40)

