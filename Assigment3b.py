# Grades

Grades=int(input("Performance:"))

if Grades>=0 and Grades<=59:
    print("F")

elif Grades>=60 and Grades<=69:
    print("D")

elif Grades>=70 and Grades<=79:
    print("C")

elif Grades>=80 and Grades<=89:
    print("B")

elif Grades>=90 and Grades<100:
    print("A")

else:
    print("Invalid Score!")